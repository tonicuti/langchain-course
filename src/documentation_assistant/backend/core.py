import os
from typing import Any, Dict
from pathlib import Path

from dotenv import load_dotenv

from langchain.agents import create_agent
from langchain.chat_models import init_chat_model
from langchain.messages import ToolMessage
from langchain.tools import tool
from langchain_pinecone import PineconeVectorStore
from langchain_ollama import OllamaEmbeddings

_env_path = Path(__file__).resolve().parent.parent / ".env"
load_dotenv(_env_path)

# Initialize the embeddings
embeddings = OllamaEmbeddings(model="embeddinggemma:latest")

# Initalize the vector store
vector_store = PineconeVectorStore(
    index_name= os.environ.get("PINECONE_NAME_INDEX"),
    embedding = embeddings,
)

# Initialize the chat model
chat_model = init_chat_model(
    model="qwen3:1.7b",
    model_provider="ollama",
)


@tool(response_format = "content_and_artifact")
def retrieve_context(query: str):
    """Retrieve relevant context from the vector store based on the query."""
    # Retrieve the top 4 revelant documents 
    retrieved_docs = vector_store.as_retriever().invoke(query, k = 4)
    
    # Serialize the retrieved documents into a single string
    serialized = "\n\n".join(
        (f"Source: {doc.metadata.get('source', 'Unknown')}\nContent: {doc.page_content}")
        for doc in retrieved_docs
    )
    
    # Return both serialized content and raw documents
    return serialized, retrieved_docs

def run_llm(query: str) -> Dict[str, Any]:
    """Run the LLM with the given query and return the response.
    
    Args:
        query (str): The query to run the LLM with.

    Returns:
        Dictionary containing:
            - answer: The answer generated by the LLM.
            - context: List of retrieved documents.
    """
    
    # Create the agent with retrieval tool.
    system_prompt = (
        "You are a helpful AI assistant that answers questions about LangChain documentation."
        "You have access to a tool that retrieves relevan documentation."
        "Use the tool to find relevant information before answering questions."
        "Always cite the sources you use in your answers."
        "If you cannot find the answer in the retrieved documentation, say 'I could not find the answer in the documentation.'"
    )
    
    # Create an agent with the chat model and retrieval tool
    agent = create_agent(
        model=chat_model,
        tools=[retrieve_context],
        system_prompt=system_prompt,
    )
    
    # Build messages list
    messages = [{
        "role": "user",
        "content": query
    }]
    
    # Invoke the agent
    response = agent.invoke({"messages": messages})
    
    # Extract the answer from the last AI message
    answer = response["messages"][-1].content
    
    # Extract context documents from ToolMessage artifacts
    context_docs = []
    for message in response["messages"]:
        # Check if this is a ToolMessage with artifact
        if isinstance(message, ToolMessage) and hasattr(message, "artifacts"):
            # The artifact should contain the list of Document objects
            if isinstance(message.artifact, list):
                context_docs.extend(message.artifacts)
            else:
                context_docs.extend(message.artifacts.get("context", []))
    
    return {
        "answer": answer,
        "context": context_docs
    }
    
if __name__ == "__main__":
    result = run_llm(query = "What are deep agents?")
    print(result)
